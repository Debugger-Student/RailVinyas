def section_to_stations(section_id: str):
    """'AAA-BBB' -> ('AAA', 'BBB', 'Station A Name', 'Station B Name')"""
    parts = section_id.split("-")
    if len(parts) != 2:
        return parts[0], parts[-1], parts[0], parts[-1]
    a, b = parts
    return a, b, station_name_lookup.get(a, a), station_name_lookup.get(b, b)


