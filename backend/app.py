@app.get("/api/sections/resolve")
def resolve_section(from_station: str, to_station: str, user=Depends(get_current_user)):
    """Turn two station codes into the section_id /api/recommend expects.
    Station-pair direction doesn't matter -- sections are undirected."""
    pair = sorted([from_station.upper(), to_station.upper()])
    section_id = "-".join(pair)
    match = traffic[traffic["section_id"] == section_id]
    if len(match) == 0:
        raise HTTPException(status_code=404,
                             detail=f"No direct section found between {from_station} and {to_station}")
    return {"section_id": section_id,
            "from_station": pair[0], "to_station": pair[1],
            "from_station_name": station_name_lookup.get(pair[0], pair[0]),
            "to_station_name": station_name_lookup.get(pair[1], pair[1])}


