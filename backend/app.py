@app.get("/api/assets")
def list_assets(user=Depends(get_current_user)):
    """Full asset register, for the Admin Panel's Asset Management tab.
    Status shown here merges the original CSV with any admin edits made
    via PATCH /api/assets/{asset_id} below (stored in railvinyas.db so
    edits persist across restarts without touching the source CSV)."""
    conn = get_db()
    overrides = {row["asset_id"]: row["status"] for row in
                 conn.execute("SELECT asset_id, status FROM asset_status_overrides").fetchall()}
    conn.close()

    result = assets.fillna("N/A").to_dict(orient="records")
    for r in result:
        if r["asset_id"] in overrides:
            r["status"] = overrides[r["asset_id"]]
    return result


class AssetStatusUpdate(BaseModel):
    status: str  # "Available" | "In Use" | "Under Repair"


@app.patch("/api/assets/{asset_id}")
def update_asset_status(asset_id: str, req: AssetStatusUpdate,
                         user=Depends(require_role("Admin"))):
    """Admin-only. Persists a status override in railvinyas.db."""
    if asset_id not in assets["asset_id"].values:
        raise HTTPException(status_code=404, detail=f"Unknown asset_id '{asset_id}'")
    if req.status not in ["Available", "In Use", "Under Repair"]:
        raise HTTPException(status_code=400, detail="status must be Available, In Use, or Under Repair")

    conn = get_db()
    conn.execute("""
        INSERT INTO asset_status_overrides (asset_id, status, updated_by, updated_at)
        VALUES (?, ?, ?, ?)
        ON CONFLICT(asset_id) DO UPDATE SET status=excluded.status,
            updated_by=excluded.updated_by, updated_at=excluded.updated_at
    """, (asset_id, req.status, user["email"], pd.Timestamp.now().isoformat()))
    conn.commit()
    conn.close()
    return {"asset_id": asset_id, "status": req.status, "updated_by": user["email"]}


