@app.get("/api/dashboard/summary")
def dashboard_summary(user=Depends(get_current_user)):
    """Real counts from the actual loaded data -- no invented numbers.
    Falls back to the most recent month PRESENT IN THE DATA if the
    real current month has no records (the synthetic dataset only
    goes up to a fixed date range)."""
    now = pd.Timestamp.now()
    this_month_mask = (blocks_full["date"].dt.year == now.year) & (blocks_full["date"].dt.month == now.month)
    count = int(this_month_mask.sum())
    reference_month = now.strftime("%B %Y")

    if count == 0:
        latest = blocks_full["date"].max()
        fallback_mask = (blocks_full["date"].dt.year == latest.year) & (blocks_full["date"].dt.month == latest.month)
        count = int(fallback_mask.sum())
        reference_month = latest.strftime("%B %Y") + " (most recent month in dataset)"

    return {
        "total_sections_monitored": int(traffic["section_id"].nunique()),
        "total_assets": int(len(assets)),
        "blocks_scheduled_this_month": count,
        "blocks_scheduled_reference_month": reference_month,
        "avg_disruption_reduction_pct": AVG_DISRUPTION_REDUCTION,  # null if Step 4 evaluation wasn't run
    }


@app.get("/api/dashboard/recent")
def dashboard_recent(limit: int = 20, user=Depends(get_current_user)):
    """Most recent maintenance blocks from the synthetic dataset, formatted
    for the dashboard table. For genuinely live requests made through this
    app, see /api/blocks/log instead."""
    recent = blocks_full.sort_values("date", ascending=False).head(limit).copy()
    now = pd.Timestamp.now()
    rows = []
    for _, r in recent.iterrows():
        a, b, a_name, b_name = section_to_stations(r["section_id"])
        rows.append({
            "section_id": r["section_id"],
            "from_station": a_name, "to_station": b_name,
            "date": r["date"].strftime("%Y-%m-%d"),
            "maintenance_type": r["maintenance_type"],
            "recommended_time": r["planned_start"],
            "traffic_level": "LOW" if r["overrun_flag"] == 0 else "MEDIUM",
            "asset_type": r["required_asset_type"],
            "status": "Completed" if r["date"] < now else "Pending",
            "priority": r["priority"],
        })
    return rows


