# ============================================================
# HOURLY SCORING
# ============================================================

def score_hour(
    section_id: str,
    hour: int,
    maintenance_type: str,
    required_asset_type: str,
    priority: str,
    weather: str,
    planned_duration_min: float,
    date: str,
):
    """
    Calculate the expected operational impact of a maintenance
    block starting at a particular hour.
    """

    # --------------------------------------------------------
    # 1. Traffic
    # --------------------------------------------------------

    try:
        trains_count, traffic_level = traffic_idx.loc[
            (section_id, hour)
        ]

    except KeyError:
        trains_count = 0.0
        traffic_level = "LOW"


    # --------------------------------------------------------
    # 2. Assets available in the requested section
    # --------------------------------------------------------

    assets_here = assets_count_idx.get(
        (section_id, required_asset_type),
        0,
    )


    # --------------------------------------------------------
    # 3. Daily asset availability
    # --------------------------------------------------------

    target_date = pd.Timestamp(date)

    day_records = avail_with_type[
        (avail_with_type["date"] == target_date)
        &
        (
            avail_with_type["asset_type"]
            == required_asset_type
        )
    ]


    if len(day_records) > 0:

        avail_pct = (
            day_records["available"] == "YES"
        ).mean()

        had_record = 1

    else:

        avail_pct = overall_type_avail.get(
            required_asset_type,
            0.7,
        )

        had_record = 0


    # --------------------------------------------------------
    # 4. Historical section overrun rate
    # --------------------------------------------------------

    section_rate = latest_section_rate.get(
        section_id,
        global_fallback_rate,
    )


    # --------------------------------------------------------
    # 5. Date features
    # --------------------------------------------------------

    d = target_date

    day_name = d.day_name()

    is_weekend = int(
        day_name in ["Saturday", "Sunday"]
    )


    # --------------------------------------------------------
    # 6. Create model input
    # --------------------------------------------------------

    raw = pd.DataFrame(
        [
            {
                "day_of_week": day_name,
                "maintenance_type": maintenance_type,
                "required_asset_type": required_asset_type,
                "priority": priority,
                "weather": weather,
                "traffic_level": traffic_level,
                "month": d.month,
                "is_weekend": is_weekend,
                "start_hour": hour,
                "trains_count": trains_count,
                "assets_of_type_in_section": assets_here,
                "asset_type_availability_pct": avail_pct,
                "had_availability_record": had_record,
                "section_historical_overrun_rate": section_rate,
                "planned_duration_min": planned_duration_min,
            }
        ]
    )


    # --------------------------------------------------------
    # 7. One-hot encode categorical variables
    # --------------------------------------------------------

    X_row = (
        pd.get_dummies(
            raw,
            columns=CATEGORICAL,
        )
        .reindex(
            columns=feature_columns,
            fill_value=0,
        )
    )


    # --------------------------------------------------------
    # 8. ML prediction
    # --------------------------------------------------------

    predicted_overrun = float(
        model.predict(X_row)[0]
    )


    # Negative overrun is not operationally useful.
    predicted_overrun = max(
        predicted_overrun,
        0.0,
    )


    # --------------------------------------------------------
    # 9. Expected duration
    # --------------------------------------------------------

    expected_total_duration = (
        planned_duration_min
        + predicted_overrun
    )


    # --------------------------------------------------------
    # 10. Disruption score
    # --------------------------------------------------------

    trains_count = float(trains_count)

    disruption_score = (
        trains_count
        * expected_total_duration
    )


    return {
        "trains_count": trains_count,

        "traffic_level": str(
            traffic_level
        ),

        "predicted_overrun_min": round(
            predicted_overrun,
            1,
        ),

        "expected_total_duration_min": round(
            expected_total_duration,
            1,
        ),

        "asset_type_availability_pct": round(
            float(avail_pct),
            2,
        ),

        "disruption_score": round(
            float(disruption_score),
            1,
        ),
    }


