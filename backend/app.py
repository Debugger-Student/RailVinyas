@app.post("/api/recommend")
def recommend(
    req: BlockRequest,
    user=Depends(get_current_user),
):
    """
    Generate an AI-assisted maintenance block recommendation.

    The system:

    1. Validates the railway section.
    2. Evaluates all 24 hours.
    3. Predicts maintenance overrun.
    4. Calculates expected duration.
    5. Calculates disruption score.
    6. Ranks candidate hours.
    7. Selects the best maintenance asset.
    """

    # --------------------------------------------------------
    # Validate section
    # --------------------------------------------------------

    if req.section_id not in traffic["section_id"].values:

        raise HTTPException(
            status_code=404,
            detail=(
                f"Unknown section_id "
                f"'{req.section_id}'"
            ),
        )


    # --------------------------------------------------------
    # Evaluate all 24 candidate hours
    # --------------------------------------------------------

    candidates = []

    for hour in range(24):

        result = score_hour(
            section_id=req.section_id,
            hour=hour,
            maintenance_type=req.maintenance_type,
            required_asset_type=req.required_asset_type,
            priority=req.priority,
            weather=req.weather,
            planned_duration_min=req.planned_duration_min,
            date=req.date,
        )

        result["start_hour"] = hour

        candidates.append(result)


    # --------------------------------------------------------
    # Rank candidates
    # --------------------------------------------------------

    ranked = sorted(
        candidates,
        key=lambda x: x["disruption_score"],
    )


    best = ranked[0]


    # --------------------------------------------------------
    # Select maintenance asset
    # --------------------------------------------------------

    asset_candidates = assets[
        assets["asset_type"]
        == req.required_asset_type
    ].copy()


    if len(asset_candidates) > 0:

        # Prefer assets whose home section matches
        # the requested railway section.
        asset_candidates["home_match"] = (
            asset_candidates["home_section_id"]
            == req.section_id
        ).astype(int)


        asset_candidates = (
            asset_candidates
            .sort_values(
                ["home_match", "status"],
                ascending=[False, True],
            )
        )


        raw_selected = (
            asset_candidates.iloc[0]
            .to_dict()
        )


        selected = {
            key: (
                value.item()
                if hasattr(value, "item")
                else value
            )

            for key, value
            in raw_selected.items()
        }

    else:

        selected = None


    # --------------------------------------------------------
    # Persist this request to the live log (see /api/blocks/log)
    # --------------------------------------------------------

    log_id = log_recommendation(req, best, selected, user)


    # --------------------------------------------------------
    # Final response
    # --------------------------------------------------------

    return {
        "section_id": req.section_id,

        "maintenance_type":
            req.maintenance_type,

        "date":
            req.date,

        "recommended_start_hour":
            best["start_hour"],

        "expected_total_duration_min":
            best["expected_total_duration_min"],

        "predicted_overrun_min":
            best["predicted_overrun_min"],

        "traffic_level":
            best["traffic_level"],

        "trains_count":
            best["trains_count"],

        "disruption_score":
            best["disruption_score"],

        "selected_asset":
            selected,

        "top_5_candidates":
            ranked[:5],

        "log_id": log_id,
    }


