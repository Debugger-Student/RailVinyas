class ApproveRequest(BaseModel):
    log_id: int


@app.post("/api/blocks/approve")
def approve_block(req: ApproveRequest, user=Depends(require_role("Admin", "Section Controller"))):
    conn = get_db()
    result = conn.execute("UPDATE block_requests_log SET status = 'Approved' WHERE id = ?", (req.log_id,))
    conn.commit()
    if result.rowcount == 0:
        conn.close()
        raise HTTPException(status_code=404, detail="Request not found")
    conn.close()
    return {"log_id": req.log_id, "status": "Approved"}


@app.get("/api/blocks/log")
def blocks_log(limit: int = 20, user=Depends(get_current_user)):
    """Real, live log of actual /api/recommend calls made through this app --
    distinct from /api/dashboard/recent, which shows the synthetic demo
    dataset. This one starts EMPTY until someone submits a real request."""
    conn = get_db()
    rows = conn.execute(
        "SELECT * FROM block_requests_log ORDER BY id DESC LIMIT ?", (limit,)
    ).fetchall()
    conn.close()
    return [dict(r) for r in rows]


