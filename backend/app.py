@app.get("/api/section-traffic/heatmap")
def section_traffic_heatmap(limit: int = 40, user=Depends(get_current_user)):
    """Top N busiest sections x 24 hours, for the heatmap page."""
    totals = traffic.groupby("section_id")["trains_count"].sum().sort_values(ascending=False)
    top_sections = totals.head(limit).index.tolist()
    subset = traffic[traffic["section_id"].isin(top_sections)]

    result = []
    for sec in top_sections:
        sec_rows = subset[subset["section_id"] == sec].set_index("hour_of_day")
        a, b, a_name, b_name = section_to_stations(sec)
        hours = []
        for h in range(24):
            if h in sec_rows.index:
                hours.append({"hour": h, "trains_count": int(sec_rows.loc[h, "trains_count"]),
                              "traffic_level": sec_rows.loc[h, "traffic_level"]})
            else:
                hours.append({"hour": h, "trains_count": 0, "traffic_level": "LOW"})
        result.append({"section_id": sec, "from_station": a_name, "to_station": b_name, "hours": hours})
    return result


