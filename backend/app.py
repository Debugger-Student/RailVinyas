class RoleUpdate(BaseModel):
    role: str  # "Admin" | "Section Controller" | "Viewer"


@app.patch("/api/admin/users/{user_id}")
def update_user_role(user_id: int, req: RoleUpdate, user=Depends(require_role("Admin"))):
    """Admin-only. Change another user's role."""
    if req.role not in ["Admin", "Section Controller", "Viewer"]:
        raise HTTPException(status_code=400, detail="role must be Admin, Section Controller, or Viewer")
    conn = get_db()
    result = conn.execute("UPDATE users SET role = ? WHERE id = ?", (req.role, user_id))
    conn.commit()
    if result.rowcount == 0:
        conn.close()
        raise HTTPException(status_code=404, detail="User not found")
    conn.close()
    return {"user_id": user_id, "role": req.role}


